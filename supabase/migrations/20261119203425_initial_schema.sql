CREATE OR REPLACE FUNCTION public.respond_to_project_invitation (
  p_invitation_id uuid,
  p_invitee_id    text,
  p_accept        boolean
)
  RETURNS jsonb
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO ''
  AS $function$
DECLARE
  v_invitation public.project_invitations%ROWTYPE;
  v_project public.projects%ROWTYPE;
  v_expected_role text;
  v_inviter_role text;
  v_actual_role text;
BEGIN

  -- 1. Vérifier les paramètres
  IF p_invitee_id IS NULL
     OR btrim(p_invitee_id) = ''
     OR p_accept IS NULL THEN
    RETURN jsonb_build_object(
      'success', false,
      'message', 'Paramètres invalides.'
    );
  END IF;

  -- 2. Verrouiller l'invitation pendant son traitement
  SELECT *
  INTO v_invitation
  FROM public.project_invitations
  WHERE id = p_invitation_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RETURN jsonb_build_object(
      'success', false,
      'message', 'Invitation introuvable.'
    );
  END IF;

  -- Seul le destinataire peut répondre
  IF v_invitation.invitee_id IS DISTINCT FROM p_invitee_id THEN
    RETURN jsonb_build_object(
      'success', false,
      'message', 'Vous ne pouvez pas répondre à cette invitation.'
    );
  END IF;

  -- Refuser les invitations déjà traitées
  IF v_invitation.status <> 'pending' THEN
    RETURN jsonb_build_object(
      'success', false,
      'message', 'Cette invitation a déjà été traitée.'
    );
  END IF;

  -- 3. Vérifier l'expiration
  IF v_invitation.expires_at <= now() THEN
    UPDATE public.project_invitations
    SET
      status = 'expired'
    WHERE id = p_invitation_id;

    RETURN jsonb_build_object(
      'success', false,
      'message', 'Cette invitation a expiré.'
    );
  END IF;

  -- 4. REFUS : aucune modification du projet
  IF p_accept = false THEN
    UPDATE public.project_invitations
    SET
      status = 'declined',
      responded_at = now()
    WHERE id = p_invitation_id;

    RETURN jsonb_build_object(
      'success', true,
      'message', 'Invitation refusée.'
    );
  END IF;

  -- 5. ACCEPTATION : verrouiller également le projet
  SELECT *
  INTO v_project
  FROM public.projects
  WHERE id = v_invitation.project_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RETURN jsonb_build_object(
      'success', false,
      'message', 'Le projet n’existe plus.'
    );
  END IF;

  -- 6. Vérifier que l'expéditeur possède toujours
  -- le projet et que la place invitée est disponible
  IF v_project.author_id = v_invitation.inviter_id
     AND v_project.publisher_id IS NULL THEN

    v_expected_role := 'Editeur';
    v_inviter_role := 'Auteur';

  ELSIF v_project.publisher_id = v_invitation.inviter_id
     AND v_project.author_id IS NULL THEN

    v_expected_role := 'Auteur';
    v_inviter_role := 'Editeur';

  ELSE
    UPDATE public.project_invitations
    SET
      status = 'cancelled',
      responded_at = now()
    WHERE id = p_invitation_id;

    RETURN jsonb_build_object(
      'success', false,
      'message', 'Cette collaboration n’est plus disponible.'
    );
  END IF;

  -- 7. Vérifier de nouveau le rôle de l'expéditeur
  SELECT role
  INTO v_actual_role
  FROM public.profiles
  WHERE id = v_invitation.inviter_id;

  IF v_actual_role IS DISTINCT FROM v_inviter_role THEN
    RETURN jsonb_build_object(
      'success', false,
      'message', 'Le rôle de l’expéditeur n’est plus valide.'
    );
  END IF;

  -- 8. Vérifier de nouveau le rôle du destinataire
  SELECT role
  INTO v_actual_role
  FROM public.profiles
  WHERE id = p_invitee_id;

  IF v_actual_role IS DISTINCT FROM v_expected_role THEN
    RETURN jsonb_build_object(
      'success', false,
      'message', 'Votre rôle ne correspond pas à cette invitation.'
    );
  END IF;

  -- 9. Associer le destinataire au projet
  IF v_expected_role = 'Auteur' THEN

    UPDATE public.projects
    SET author_id = p_invitee_id
    WHERE id = v_project.id
      AND author_id IS NULL
      AND publisher_id = v_invitation.inviter_id;

  ELSE

    UPDATE public.projects
    SET publisher_id = p_invitee_id
    WHERE id = v_project.id
      AND publisher_id IS NULL
      AND author_id = v_invitation.inviter_id;

  END IF;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Association impossible';
  END IF;

  -- 10. Marquer l'invitation comme acceptée
  UPDATE public.project_invitations
  SET
    status = 'accepted',
    responded_at = now()
  WHERE id = p_invitation_id;

  RETURN jsonb_build_object(
    'success', true,
    'message', 'Invitation acceptée avec succès.',
    'project_id', v_project.id
  );

END;
$function$;

REVOKE ALL ON FUNCTION "public"."respond_to_project_invitation"(uuid, text, boolean) FROM PUBLIC, "anon", "authenticated";

CREATE OR REPLACE FUNCTION public.rls_auto_enable()
  RETURNS event_trigger
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO 'pg_catalog'
  AS $function$
DECLARE
  cmd record;
BEGIN
  FOR cmd IN
    SELECT *
    FROM pg_event_trigger_ddl_commands()
    WHERE command_tag IN ('CREATE TABLE', 'CREATE TABLE AS', 'SELECT INTO')
      AND object_type IN ('table','partitioned table')
  LOOP
     IF cmd.schema_name IS NOT NULL AND cmd.schema_name IN ('public') AND cmd.schema_name NOT IN ('pg_catalog','information_schema') AND cmd.schema_name NOT LIKE 'pg_toast%' AND cmd.schema_name NOT LIKE 'pg_temp%' THEN
      BEGIN
        EXECUTE format('alter table if exists %s enable row level security', cmd.object_identity);
        RAISE LOG 'rls_auto_enable: enabled RLS on %', cmd.object_identity;
      EXCEPTION
        WHEN OTHERS THEN
          RAISE LOG 'rls_auto_enable: failed to enable RLS on %', cmd.object_identity;
      END;
     ELSE
        RAISE LOG 'rls_auto_enable: skip % (either system schema or not in enforced list: %.)', cmd.object_identity, cmd.schema_name;
     END IF;
  END LOOP;
END;
$function$;

CREATE OR REPLACE FUNCTION public.save_encrypted_version (
  p_user_id       text,
  p_project_id    uuid,
  p_storage_path  text,
  p_file_name     text,
  p_file_hash     text,
  p_encryption_iv text,
  p_wrapped_key   text
)
  RETURNS uuid
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO ''
  AS $function$
DECLARE
  v_version_id uuid;
BEGIN

  -- 1. Vérifier les droits sur le projet
  IF NOT EXISTS (
    SELECT 1
    FROM public.projects
    WHERE id = p_project_id
      AND (
        author_id = p_user_id
        OR publisher_id = p_user_id
      )
  ) THEN
    RAISE EXCEPTION 'Accès au projet refusé';
  END IF;

  -- 2. Vérifier l'identité cryptographique
  IF NOT EXISTS (
    SELECT 1
    FROM public.user_crypto_keys
    WHERE user_id = p_user_id
  ) THEN
    RAISE EXCEPTION 'Identité cryptographique absente';
  END IF;

  -- 3. Vérifier le chemin de stockage
  IF p_storage_path IS NULL
     OR p_storage_path !~ (
       '^' || p_project_id::text ||
       '/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.enc$'
     ) THEN
    RAISE EXCEPTION 'Chemin de stockage invalide';
  END IF;

  -- 4. Vérifier l'existence du fichier
  IF NOT EXISTS (
    SELECT 1
    FROM storage.objects
    WHERE bucket_id = 'manuscripts'
      AND name = p_storage_path
  ) THEN
    RAISE EXCEPTION 'Fichier introuvable dans le stockage';
  END IF;

  -- 5. Vérifier les paramètres cryptographiques
  IF p_file_hash IS NULL
     OR p_file_hash !~ '^[0-9a-f]{64}$'

     OR p_encryption_iv IS NULL
     OR p_encryption_iv !~ '^[A-Za-z0-9+/]{16}$'

     OR p_wrapped_key IS NULL

     -- CORRECTION : longueur vérifiée séparément
     OR length(p_wrapped_key) <> 512

     -- CORRECTION : plus de répétition {512}
     OR p_wrapped_key !~ '^[A-Za-z0-9+/]+$'

  THEN
    RAISE EXCEPTION 'Métadonnées cryptographiques invalides';
  END IF;

  -- 6. Vérifier le nom du fichier
  IF p_file_name IS NULL
     OR length(btrim(p_file_name)) = 0
     OR length(p_file_name) > 255
  THEN
    RAISE EXCEPTION 'Nom de fichier invalide';
  END IF;

  -- 7. Enregistrer la version
  INSERT INTO public.versions (
    project_id,
    storage_path,
    file_name,
    file_hash,
    encryption_iv,
    encryption_version,
    created_at
  )
  VALUES (
    p_project_id,
    p_storage_path,
    p_file_name,
    p_file_hash,
    p_encryption_iv,
    1,
    now()
  )
  RETURNING id INTO v_version_id;

  -- 8. Enregistrer la clé de fichier chiffrée
  INSERT INTO public.version_access_keys (
    version_id,
    user_id,
    encrypted_key
  )
  VALUES (
    v_version_id,
    p_user_id,
    p_wrapped_key
  );

  RETURN v_version_id;

END;
$function$;

REVOKE ALL ON FUNCTION "public"."save_encrypted_version"(text, uuid, text, text, text, text, text) FROM PUBLIC, "anon", "authenticated";

CREATE OR REPLACE FUNCTION public.share_version_access_key (
  p_sender_id         text,
  p_project_id        uuid,
  p_version_id        uuid,
  p_recipient_id      text,
  p_recipient_modulus text,
  p_wrapped_key       text
)
  RETURNS boolean
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO ''
  AS $function$
DECLARE
  v_project public.projects%ROWTYPE;
  v_inserted integer;
BEGIN
  IF p_sender_id IS NULL OR p_recipient_id IS NULL
     OR p_sender_id = p_recipient_id THEN
    RAISE EXCEPTION 'Identités invalides';
  END IF;

  -- Verrouiller le projet jusqu'à la fin de l'opération : la collaboration
  -- ne doit pas pouvoir changer entre le contrôle et l'attribution d'accès.
  SELECT * INTO v_project
  FROM public.projects
  WHERE id = p_project_id
  FOR SHARE;

  IF NOT FOUND OR v_project.author_id IS NULL
     OR v_project.publisher_id IS NULL OR NOT (
       (v_project.author_id = p_sender_id
        AND v_project.publisher_id = p_recipient_id)
       OR
       (v_project.publisher_id = p_sender_id
        AND v_project.author_id = p_recipient_id)
     ) THEN
    RAISE EXCEPTION 'Collaborateurs du projet non autorisés';
  END IF;

  -- Le rattachement doit provenir d'une invitation effectivement acceptée.
  IF NOT EXISTS (
    SELECT 1 FROM public.project_invitations
    WHERE project_id = p_project_id AND status = 'accepted'
      AND (
        (inviter_id = p_sender_id AND invitee_id = p_recipient_id)
        OR
        (inviter_id = p_recipient_id AND invitee_id = p_sender_id)
      )
  ) THEN
    RAISE EXCEPTION 'Consentement de collaboration non confirmé';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM public.versions
    WHERE id = p_version_id AND project_id = p_project_id
      AND encryption_version = 1
  ) THEN
    RAISE EXCEPTION 'Version chiffrée introuvable';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM public.version_access_keys
    WHERE version_id = p_version_id AND user_id = p_sender_id
  ) THEN
    RAISE EXCEPTION 'L’expéditeur ne possède pas la clé de cette version';
  END IF;

  -- Empêche d'attribuer une clé enveloppée pour une autre identité publique.
  IF NOT EXISTS (
    SELECT 1 FROM public.user_crypto_keys
    WHERE user_id = p_recipient_id
      AND public_key_jwk ->> 'n' = p_recipient_modulus
      AND public_key_jwk ->> 'e' = 'AQAB'
  ) THEN
    RAISE EXCEPTION 'La clé publique du destinataire a changé';
  END IF;

  -- RSA-OAEP 3072 donne un bloc de 384 octets, soit 512 caractères Base64.
  IF p_wrapped_key IS NULL
     OR length(p_wrapped_key) <> 512
     OR p_wrapped_key !~ '^[A-Za-z0-9+/]+$' THEN
    RAISE EXCEPTION 'Clé de version chiffrée invalide';
  END IF;

  INSERT INTO public.version_access_keys (version_id, user_id, encrypted_key)
  VALUES (p_version_id, p_recipient_id, p_wrapped_key)
  ON CONFLICT (version_id, user_id) DO NOTHING;

  GET DIAGNOSTICS v_inserted = ROW_COUNT;
  RETURN v_inserted = 1;
END;
$function$;

